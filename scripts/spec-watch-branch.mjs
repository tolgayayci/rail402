#!/usr/bin/env node
// Turns detected spec drift into a DRAFT branch — never a merge.
//
// One branch per drift wave: `spec-drift/<fingerprint>`, cut from the current main. It carries:
//
//   • docs/research/spec-pins.json bumped to the new upstream SHAs (repoHead + snapshotDate too)
//   • docs/research/drift/DRIFT-<fingerprint>.md — the full diff excerpts, affected modules, and
//     the test report, so the reviewer (human or Copilot coding agent) starts from evidence, not
//     from a re-derivation
//
// Merging this branch ASSERTS conformance to the new spec text, which is exactly why automation
// must never do it: the tracking issue's checklist (re-read the specs, update SPEC_SNAPSHOT.md,
// re-run conformance) has to be completed by someone accountable first. This script only pushes
// the branch; nothing here opens or merges anything (CLAUDE.md §3.8c: all of it stays in this
// repository).
//
// Idempotent: if the branch for this fingerprint already exists on origin, it is left untouched —
// a weekly re-run with an unchanged drift set must not force-push over review-in-progress work.
//
// Usage: node scripts/spec-watch-branch.mjs --report report.json [--tests tests.json] [--dry-run]

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";

const DRY = process.argv.includes("--dry-run");

function arg(name) {
  const i = process.argv.indexOf(name);
  return i !== -1 ? process.argv[i + 1] : null;
}

const git = (args, opts = {}) =>
  execFileSync("git", args, { encoding: "utf8", maxBuffer: 16 * 1024 * 1024, ...opts }).trim();

function output(branch) {
  if (process.env.GITHUB_OUTPUT)
    writeFileSync(process.env.GITHUB_OUTPUT, `branch=${branch}\n`, { flag: "a" });
}

const report = JSON.parse(readFileSync(arg("--report"), "utf8"));
const testsPath = arg("--tests");
const tests = testsPath && existsSync(testsPath) ? JSON.parse(readFileSync(testsPath, "utf8")) : null;

if (report.driftCount === 0) {
  console.log("spec-watch-branch: no drift — no branch to draft.");
  process.exit(0);
}

const branch = `spec-drift/${report.fingerprint}`;

if (!DRY && git(["ls-remote", "--heads", "origin", branch])) {
  console.log(`spec-watch-branch: ${branch} already exists on origin — leaving it untouched.`);
  output(branch);
  process.exit(0);
}

// Work in a throwaway worktree so the caller's checkout is never disturbed mid-workflow.
const wt = join(tmpdir(), `spec-drift-${report.fingerprint}`);
rmSync(wt, { recursive: true, force: true });
git(["worktree", "prune"]);
git(["worktree", "add", "-B", branch, wt, "HEAD"]);

try {
  // ── bump the pins ───────────────────────────────────────────────────────────
  const pinsPath = join(wt, "docs/research/spec-pins.json");
  const pins = JSON.parse(readFileSync(pinsPath, "utf8"));
  for (const d of report.drifted) pins.files[d.path] = d.current.slice(0, 8);
  pins.repoHead = report.upstreamHead;
  pins.snapshotDate = new Date().toISOString().slice(0, 10);
  writeFileSync(pinsPath, JSON.stringify(pins, null, 2) + "\n");

  // ── the drift doc ───────────────────────────────────────────────────────────
  const doc = [];
  doc.push(`# Upstream spec drift ${report.fingerprint}`);
  doc.push("");
  doc.push(
    `> DRAFT generated by \`.github/workflows/spec-watch.yml\` on ${report.checkedAt}. Merging this`,
    `> branch asserts conformance to the new spec SHAs — complete the tracking issue's checklist`,
    `> first (re-read each spec, update \`docs/research/SPEC_SNAPSHOT.md\`, re-run conformance).`,
    `> Automation never merges this; a human does.`,
  );
  doc.push("");
  doc.push(`Upstream head: \`${report.upstreamHead}\` · previous snapshot: ${report.snapshotDate}`);
  doc.push("");
  if (tests) {
    doc.push(`## Test verdict: ${tests.verdict.toUpperCase()}`);
    doc.push("");
    doc.push(tests.reason);
    doc.push("");
    doc.push(`| Check | Result | Detail |`, `|---|---|---|`);
    for (const s of tests.suites) doc.push(`| ${s.name} | ${s.outcome} | ${s.detail} |`);
    doc.push("");
  } else {
    doc.push(`## Test verdict: not available`, ``, `The test steps produced no report this run.`, ``);
  }
  for (const d of report.drifted) {
    doc.push(`## \`${d.path}\` — \`${d.pinned}\` → \`${d.current.slice(0, 8)}\``);
    doc.push("");
    doc.push(`Last upstream commit: ${d.subject} (\`${d.currentShort}\`, ${d.date})`);
    if (d.summary) doc.push(`What this spec governs for us: ${d.summary}`);
    if (d.modules?.length)
      doc.push(
        `Implemented in: ${d.modules.map(m => `\`${m.path}\`${m.humanOnly ? " ⚠️ human-only" : ""}`).join(", ")}`,
      );
    // Four-backtick fence: spec files are markdown, so their diffs legitimately contain ``` blocks.
    doc.push("", "````diff", d.diffExcerpt, "````", d.diffTruncated ? "(diff truncated)" : "", "");
  }
  for (const m of report.missing) {
    doc.push(`## \`${m.path}\` — REMOVED upstream (was \`${m.pinned}\`)`);
    doc.push("", "The pin is left in place; decide whether to drop it or follow a renamed file.", "");
  }

  const driftDir = join(wt, "docs/research/drift");
  mkdirSync(driftDir, { recursive: true });
  writeFileSync(join(driftDir, `DRIFT-${report.fingerprint}.md`), doc.join("\n"));

  if (DRY) {
    console.log(`[dry-run] would commit and push ${branch}:`);
    console.log(git(["-C", wt, "status", "--short"]));
  } else {
    git(["-C", wt, "add", "docs/research/spec-pins.json", "docs/research/drift"]);
    git(
      [
        "-C",
        wt,
        "-c",
        "user.name=rail402 spec-watch",
        "-c",
        "user.email=noreply@github.com",
        "commit",
        "-m",
        `Draft spec pin update for upstream drift ${report.fingerprint}`,
      ],
      { stdio: ["ignore", "pipe", "pipe"] },
    );
    git(["-C", wt, "push", "origin", `${branch}:refs/heads/${branch}`]);
    console.log(`spec-watch-branch: pushed ${branch}.`);
  }
  output(branch);
} finally {
  rmSync(wt, { recursive: true, force: true });
  try {
    git(["worktree", "prune"]);
    git(["branch", "-D", branch]);
  } catch {
    /* local branch cleanup is best-effort; the pushed ref is what matters */
  }
}
